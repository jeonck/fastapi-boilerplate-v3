"""
Authentication API Routes (FastAPI Users)

Mounts the routers generated by FastAPI Users:
- /auth/jwt/login, /auth/jwt/logout
- /auth/register
- /auth/forgot-password, /auth/reset-password
- /auth/request-verify-token, /auth/verify
- /users/me, /users/{id}

Auth endpoints are rate limited to slow down brute-force attacks.
"""

from fastapi import APIRouter, Depends

from app.core.config import settings
from app.core.limiter import rate_limit
from app.core.users import auth_backend, fastapi_users
from app.schemas.user import UserCreate, UserRead, UserUpdate

auth_limit = Depends(
    rate_limit(settings.auth_rate_limit_times, settings.auth_rate_limit_seconds)
)

router = APIRouter()

router.include_router(
    fastapi_users.get_auth_router(auth_backend),
    prefix="/auth/jwt",
    tags=["Auth"],
    dependencies=[auth_limit],
)
router.include_router(
    fastapi_users.get_register_router(UserRead, UserCreate),
    prefix="/auth",
    tags=["Auth"],
    dependencies=[auth_limit],
)
router.include_router(
    fastapi_users.get_reset_password_router(),
    prefix="/auth",
    tags=["Auth"],
    dependencies=[auth_limit],
)
router.include_router(
    fastapi_users.get_verify_router(UserRead),
    prefix="/auth",
    tags=["Auth"],
    dependencies=[auth_limit],
)
router.include_router(
    fastapi_users.get_users_router(UserRead, UserUpdate),
    prefix="/users",
    tags=["Users"],
)
