"""
Item Model

Sample resource whose CRUD endpoints are generated by FastAPI-CrudRouter.

Business rules are enforced by the database, not only by Python code:
- `uq_items_name`: item names are unique. A check-then-insert in Python
  (`if exists: raise ...`) is racy under concurrent requests; the unique
  constraint is not. Violations become `409 Conflict` (see app/core/errors.py).
- `ck_items_price_non_negative`: guards writes that bypass the API schemas.

Money is stored as NUMERIC (exact), never FLOAT.
"""

from datetime import datetime, timezone
from decimal import Decimal

from sqlalchemy import CheckConstraint, DateTime, Integer, Numeric, String, Text
from sqlalchemy.orm import Mapped, mapped_column

from app.core.database import Base


def _utcnow() -> datetime:
    return datetime.now(timezone.utc)


class Item(Base):
    """Sample item resource."""

    __tablename__ = "items"
    __table_args__ = (
        CheckConstraint("price >= 0", name="ck_items_price_non_negative"),
    )

    id: Mapped[int] = mapped_column(Integer, primary_key=True, index=True)
    name: Mapped[str] = mapped_column(
        String(100), unique=True, index=True
    )
    description: Mapped[str | None] = mapped_column(Text, nullable=True)
    price: Mapped[Decimal] = mapped_column(Numeric(12, 2), default=Decimal("0"))
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=_utcnow)
